/**
 * feature-cards-demo.js — 피처 카드 여섯 장
 *
 * 로그 한 줄이 모델에 들어갈 숫자 묶음이 되고, 그 값이 학습과 서빙 양쪽에 닿기까지의 자리 하나가 카드 한 장이다.
 * 왼쪽에 들어오는 것, 가운데에 처리하는 자리(회색 상자), 오른쪽에 나오는 결과, 맨 아래 한 줄에 숫자다.
 * 색은 css/style.css 의 카드 부품 블록이 정한다 — 파랑 놓여 있는 데이터(저장소, 표, 만들어 둔 값),
 * 벽돌색 지금 오는 것(요청, 이벤트)과 문제가 되는 자리, 먹색 모델과 서버, 회색 만드는 작업(배치, 스트림, 변환).
 * 점선 상자는 적어 둔 것(정의, 규칙).
 *
 * 숫자는 전부 그 글의 가상 값이다 — 피처 스토어 글(갱신 주기 표, 시간 예산, 폴백 계층)과
 * CTR 피처 엔지니어링 글(로그 필드 표, 시퀀스 길이 20)에서 가져왔고 새로 만든 값은 없다.
 *
 * ?card=key 가 붙으면 그 카드만 남긴다 (글 안에 iframe 으로 넣을 때 쓴다).
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { esc, T, tw, box, tag, srv, table, db, tool, clock, user, list, arrow, dots, burst, svg, hbar, ruler, lines } = window.CardKit;
    const has = id => !!document.getElementById(id);
    const path = (id, d) => `<path id="${id}" d="${d}" fill="none" stroke="none"/>`;

    // ---------- 1. 세 갈래 파이프라인 — 신선하게 만들수록 비싸다 ----------
    (function () {
        const S = 'ft-threepipes'; if (!has(S)) return; let s = '';
        s += T(40, 24, '피처는 신선도가 다르고, 신선한 것일수록 자주 돌려야 합니다', 'lbl sm');
        s += T(40, 46, '길', 'lbl sm') + T(116, 46, '만드는 주기', 'lbl sm') + T(232, 46, '보기', 'lbl sm') + T(392, 46, '값이 얼마나 묵나', 'lbl sm');
        const rows = [
            ['배치', '하루 한 번', '유저 7일 클릭률', 1.0, '최대 24시간', 'c'],
            ['스트리밍', '1분에서 5분', '최근 5분 클릭 수', 0.21, '최대 5분', 'a'],
            ['실시간', '요청마다', '기기, 시간대', 0.02, '안 묵음', 'b'],
        ];
        rows.forEach((r, i) => {
            const y = 58 + i * 46;
            s += tag(40, y, r[0], r[5]);
            s += T(116, y + 13, r[1], 'lbl k');
            s += T(232, y + 13, r[2], 'lbl k');
            s += hbar(392, y + 2, 88, r[3], r[5], 15);
            s += T(392, y + 34, r[4], 'lbl sm');
        });
        s += T(40, 214, '한 요청에서 셋을 같이 가져와 숫자 묶음 하나로 합칩니다', 'lbl sm');
        s += tag(40, 224, '셋을 나란히 가져오면 조회가 1ms. 차례로 가져오면 4ms', 'k');
        s += T(40, 270, '신선하게 만들수록 비쌉니다. 그래서 피처마다 다른 길에 태웁니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 2. 같은 피처, 읽는 곳이 둘 ----------
    (function () {
        const S = 'ft-twostores'; if (!has(S)) return; let s = '';
        s += T(40, 24, '정의는 하나입니다', 'lbl sm');
        s += list(40, 32, 168, 40, [{ t: '유저 7일 클릭률', cls: 'h' }, '지난 7일 클릭 ÷ 노출']);
        s += arrow('ft21', 'M210,44 C238,44 244,34 262,34', 'a', { svg: S, dash: true });
        s += arrow('ft22', 'M210,60 C238,60 244,150 262,150', 'a', { svg: S, dash: true });
        s += dots('ft21', 'a', { n: 1, dur: 2.6 }) + dots('ft22', 'a', { n: 1, dur: 2.6 });
        s += T(266, 26, '학습이 읽는 곳', 'lbl k');
        s += db(300, 44, { label: '오프라인 저장소' });
        s += T(374, 44, '그 시점으로 되돌려 잇습니다', 'lbl sm');
        s += T(374, 58, '2026-08-01 노출에는', 'lbl sm');
        s += T(374, 72, '그날 자정까지의 값만', 'lbl sm');
        s += T(266, 142, '서빙이 읽는 곳', 'lbl k');
        s += db(300, 160, { label: '온라인 저장소' });
        s += T(374, 160, '지금 값 하나만 있습니다', 'lbl sm');
        s += T(374, 174, '키 하나로 1ms 안에', 'lbl sm');
        s += T(374, 188, '과거는 안 남아 있습니다', 'lbl sm');
        s += tag(40, 106, '두 곳이 같은 값이어야 맞습니다', 'a');
        s += tag(40, 132, '한쪽만 고치면 실서빙이 떨어집니다', 'b');
        s += lines(40, 176, ['정의를 한 곳에만 적고', '양쪽이 그것을 불러 씁니다']);
        s += T(40, 270, '정의는 하나인데 읽는 곳이 둘입니다. 둘이 어긋나면 모델이 조용히 틀립니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 3. 갱신 주기는 피처마다 정한다 ----------
    (function () {
        const S = 'ft-freshness'; if (!has(S)) return; let s = '';
        s += T(40, 24, '왼쪽이 자주 만드는 것, 오른쪽이 드물게 만드는 것입니다', 'lbl sm');
        s += ruler(40, 58, 440, [[40, '요청마다', '', 'lbl b'], [150, '1분', ''], [260, '5분', ''], [370, '1시간', ''], [480, '1일', '']], { h: 14, fill: 0, fillCls: 'a' });
        s += path('ftf1', 'M42,65 L478,65') + dots('ftf1', 'k', { n: 2, dur: 5 });
        const items = [
            [40, 108, '기기, 시간대', 'b'],
            [150, 134, '캠페인 남은 예산', 'a'],
            [260, 160, '유저 최근 클릭 수', 'a'],
            [370, 186, '광고 과거 클릭률', 'c'],
            [370, 212, '유저 7일 클릭률', 'c'],
        ];
        items.forEach(it => {
            s += `<line class="tick" x1="${it[0]}" y1="74" x2="${it[0]}" y2="${it[1] - 4}"/>`;
            s += tag(it[0], it[1] - 14, it[2], it[3]);
        });
        s += T(40, 244, '기기는 요청에 실려 와 계산이 거의 공짜입니다', 'lbl sm');
        s += T(40, 258, '7일 클릭률을 1분마다 다시 세면 값만 비싸집니다', 'lbl sm');
        s += T(40, 286, '신선도는 피처마다 정합니다. 다 실시간으로 만들면 값만 비싸집니다', 'lbl');
        svg(S, s, 316);
    })();

    // ---------- 4. 피처가 안 올 때 무엇을 넣나 ----------
    (function () {
        const S = 'ft-fallback'; if (!has(S)) return; let s = '';
        s += T(40, 24, '요청은 8ms 안에 답해야 하고, 저장소는 가끔 늦습니다', 'lbl sm');
        s += tag(40, 34, '요청 한 건', 'b');
        s += arrow('ftb1', 'M40,74 L116,74', 'b', { svg: S });
        s += dots('ftb1', 'b', { n: 2, dur: 2 });
        s += tool(120, 56, 104, { label: '피처 조회', sub: '1ms 안에 와야 합니다', clock: true });
        s += arrow('ftb2', 'M226,66 C246,66 250,50 264,50', 'a', { svg: S });
        s += arrow('ftb3', 'M226,84 C246,84 250,112 264,112', 'b', { svg: S });
        s += dots('ftb2', 'a', { n: 2, dur: 2.2 }) + dots('ftb3', 'b', { n: 1, dur: 3 });
        s += tag(268, 40, '왔습니다. 그대로 씁니다', 'a');
        s += T(268, 104, '안 왔습니다. 위에서부터 씁니다', 'lbl b');
        const steps = [
            ['1', '조금 전에 받아 둔 같은 키의 값', 'a'],
            ['2', '그 무리의 평균값 (지면별, 업종별)', 'c'],
            ['3', '전체 평균 pCTR 하나', 'k'],
        ];
        steps.forEach((st, i) => {
            const y = 118 + i * 30;
            s += box(268, y, 20, 20, st[0], st[2], 10);
            s += T(296, y + 14, st[1], 'lbl k');
        });
        s += list(40, 118, 200, 76, [{ t: '무엇을 넣었는지 로그에 남깁니다', cls: 'h' }, '안 남기면 그 요청이 왜 나빴는지', '나중에 못 찾습니다', { t: '폴백 비율이 오르면 알람', cls: 'b' }]);
        s += T(40, 214, '아래로 갈수록 답은 나가지만 맞는 정도가 떨어집니다', 'lbl sm');
        s += T(40, 270, '피처가 없다고 응답을 안 낼 수는 없습니다. 무엇으로 채울지 미리 정합니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 5. 로그 한 줄이 숫자 묶음이 되기까지 ----------
    (function () {
        const S = 'ft-rowtovector'; if (!has(S)) return; let s = '';
        s += T(40, 24, '로그 한 줄 (대부분이 숫자가 아니라 번호입니다)', 'lbl sm');
        s += list(40, 32, 176, 88, ['ad_id  8837201', 'user_id  u_5512883', 'ts  2026-08-02 21:14', 'recent_views  [3312, 981, …]', 'ad_ctr_7d  0.0231']);
        const fams = [
            ['번호는 칸으로', '해시 뒤 임베딩', 'a'],
            ['시각은 쪼개서', '시간대 24칸, 요일 7칸', 'c'],
            ['이력은 길이를 맞춰', '최근 20개 + 마스크', 'c'],
            ['집계는 창으로', 'D-7 에서 D-1 까지', 'a'],
        ];
        fams.forEach((f, i) => {
            const y = 36 + i * 44;
            s += arrow('ftr' + i, `M220,${76} C244,${76} 248,${y + 14} 262,${y + 14}`, f[2], { svg: S });
            s += dots('ftr' + i, f[2], { n: 1, dur: 2.4 + i * 0.3 });
            s += tag(266, y, f[0], f[2]);
            s += T(266, y + 30, f[1], 'lbl sm');
        });
        s += arrow('ftr4', 'M440,214 L440,238', 'k', { svg: S });
        s += dots('ftr4', 'k', { n: 1, dur: 2 });
        s += tag(354, 240, '숫자 묶음 하나가 모델로', 'k');
        s += T(40, 140, '같은 줄인데 넣는 방법이 넷입니다', 'lbl sm');
        s += T(40, 154, '어느 가족인지가 정해지면', 'lbl sm');
        s += T(40, 168, '넣는 방법도 따라 정해집니다', 'lbl sm');
        s += T(40, 270, '로그 한 줄은 그대로 못 들어갑니다. 네 갈래로 바꿔 숫자 묶음 하나가 됩니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 6. 사람마다 다른 이력을 길이 20 으로 ----------
    (function () {
        const S = 'ft-sequence'; if (!has(S)) return; let s = '';
        s += T(40, 24, '모델이 받는 칸은 20개로 고정입니다. 사람마다 이력 개수는 다릅니다', 'lbl sm');
        const W = 10, STEP = 12;                       // 칸 하나와 칸 사이. 37칸이 그림 안에 들어가는 크기
        const cell = (x, y, cls) => `<rect class="f-${cls}" x="${x}" y="${y}" width="${W}" height="15"/>`;
        const empty = (x, y, cls) => `<rect class="${cls}" x="${x}" y="${y}" width="${W}" height="15"/>`;

        // 이력 37개 — 왼쪽이 오래된 것, 오른쪽이 최근. 오래된 17개를 잘라낸다
        s += T(40, 52, '이력 37개인 사람', 'lbl k');
        for (let i = 0; i < 17; i++) s += cell(40 + i * STEP, 60, 'b');
        for (let i = 17; i < 37; i++) s += cell(40 + i * STEP, 60, 'a');
        s += `<line class="tick" x1="${40 + 17 * STEP - 1}" y1="56" x2="${40 + 17 * STEP - 1}" y2="79"/>`;
        s += T(40, 90, '오래된 17개는 잘라냅니다', 'lbl b');
        s += T(40 + 17 * STEP, 90, '최근 20개만 씁니다', 'lbl k');

        // 이력 5개 — 빈 칸 15개를 채운다
        s += T(40, 126, '이력 5개인 사람', 'lbl k');
        for (let i = 0; i < 5; i++) s += cell(40 + i * STEP, 134, 'a');
        for (let i = 5; i < 20; i++) s += empty(40 + i * STEP, 134, 'list');
        s += T(40, 164, '진짜 5개', 'lbl sm');
        s += T(40 + 5 * STEP, 164, '빈 칸 15개를 0 으로 채웁니다', 'lbl sm');
        s += tag(320, 130, '0 도 번호입니다', 'b');
        s += T(320, 164, '모델이 계산에 넣습니다', 'lbl sm');

        // 마스크 — 어디가 진짜인지
        s += T(40, 196, '그래서 어디가 진짜인지 알려 주는 칸을 하나 더 만듭니다', 'lbl sm');
        for (let i = 0; i < 5; i++) s += cell(40 + i * STEP, 206, 'k');
        for (let i = 5; i < 20; i++) s += empty(40 + i * STEP, 206, 'track');
        s += T(40 + 21 * STEP, 218, '이것이 마스크입니다', 'lbl k');
        s += T(40, 236, '먹색 자리만 계산에 넣고 빈 칸은 뺍니다', 'lbl sm');

        s += T(40, 270, '사람마다 길이가 다른 것을 자르고 채워 20 으로 맞춥니다', 'lbl');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
