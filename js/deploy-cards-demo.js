/**
 * deploy-cards-demo.js — 배포 카드 다섯 장
 *
 * 새 모델이 실제 요청을 받기 시작하는 길에서 사람이 정하는 자리 하나가 카드 한 장. 왼쪽에 들어오는 것,
 * 가운데에 처리하는 자리(회색 상자), 오른쪽에 나오는 결과, 맨 아래에 숫자 한 줄이다.
 * 색은 css/style.css 의 카드 부품 블록이 정한다 — 파랑 놓여 있는 것(로그, 가중치 규칙), 벽돌색 지금 오는 것
 * (요청, 알람), 먹색 모델과 서버, 회색 만드는 작업(복사, 가중치 바꾸기, 웜업). 점선 상자는 적어 둔 것(게이트 조건).
 * 숫자는 전부 설계 문서의 표준 가상 값이다 — 요청 초당 2,639건, 모델 서버 12대, 8ms 초과율 평소 4.62%,
 * 카나리 1%(5분) → 10%(30분) → 50%(30분) → 100%, 07:04 알람부터 07:18 확인까지 14분, 웜업 200건 20초.
 *
 * ?card=key 가 붙으면 그 카드만 남긴다 (글 안에 iframe 으로 넣을 때 쓴다).
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { esc, T, box, tag, srv, table, tool, user, list, arrow, dots, svg, lines } = window.CardKit;
    const has = id => !!document.getElementById(id);
    // 눈에 보이지 않는 길 — 점만 흐르게 할 때
    const path = (id, d) => `<path id="${id}" d="${d}" fill="none" stroke="none"/>`;
    // 채운 칸 하나 — 시간선의 한 구간. 글자는 칸 가운데
    const seg = (x, y, w, h, txt, cls, fs = 10) => {
        let s = `<rect class="${cls}" x="${x}" y="${y}" width="${w}" height="${h}"/>`;
        if (txt) s += `<text class="${cls === 'track' ? 'lbl k' : 'on'}" x="${x + w / 2}" y="${y + h / 2 + fs * 0.36}" text-anchor="middle" style="font-size:${fs}px">${esc(txt)}</text>`;
        return s;
    };
    const tick = (x, y1, y2) => `<line class="tick" x1="${x}" y1="${y1}" x2="${x}" y2="${y2}"/>`;

    // ---------- 1. 섀도 — 계산만 하고 응답에는 안 쓴다 ----------
    (function () {
        const S = 'dp-shadow'; if (!has(S)) return; let s = '';
        s += T(40, 26, '요청 초당 2,639건이 오면 API 서버가 둘로 복사합니다', 'lbl sm');
        s += arrow('dps1', 'M40,76 L106,76', 'b', { svg: S });
        s += dots('dps1', 'b', { n: 3, dur: 2.4 });
        s += srv(110, 48, { cls: 'k', label: 'API 서버' });
        s += arrow('dps2', 'M156,76 L172,76', 'k', { svg: S });
        s += tool(176, 56, 84, { label: '요청 복사' });
        s += arrow('dps3', 'M262,68 C282,68 286,52 298,52', 'k', { svg: S });
        s += arrow('dps4', 'M262,84 C282,84 286,166 298,166', 'k', { svg: S });
        s += dots('dps3', 'k', { n: 1, dur: 2 }) + dots('dps4', 'k', { n: 1, dur: 2 });
        s += srv(302, 26, { cls: 'k', label: 'v417 운영' });
        s += arrow('dps5', 'M348,52 L384,52', 'a', { svg: S });
        s += dots('dps5', 'a', { n: 1, dur: 1.6 });
        s += user(400, 40, '');
        s += T(400, 84, '응답이 됩니다', 'lbl k', 'middle');
        s += srv(302, 140, { cls: 'k', label: 'v418 새 모델' });
        s += arrow('dps6', 'M348,166 L384,166', 'a', { svg: S, dash: true });
        s += dots('dps6', 'a', { n: 1, dur: 1.6 });
        s += table(392, 140, { label: '로그: 예측값 둘' });
        s += lines(420, 224, ['v417 0.0412, v418 0.0455', '같은 요청에 두 점수'], 'lbl sm', 13, 'middle');
        s += tag(40, 150, '응답은 v417 것만 씁니다. 손해 0', 'a');
        s += tag(40, 176, '비용 2배: 모델 서버 12대가 더 듭니다', 'b');
        s += tag(40, 202, '클릭은 못 봅니다 (나간 광고는 v417 것)', 'k');
        s += lines(40, 250, ['전날 오후 세 시간 섀도. 지연과 분포가 v417 과 거의 같았습니다']);
        s += T(40, 270, '새 모델은 계산만 하고 응답에는 안 씁니다. 손해 0, 비용 2배, 클릭은 못 봅니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 2. 카나리 — 1, 10, 50, 100 으로 넓힌다 ----------
    (function () {
        const S = 'dp-canary'; if (!has(S)) return; let s = '';
        s += T(40, 26, '게이트웨이 규칙의 가중치 한 줄이 요청을 나눕니다', 'lbl sm');
        s += tag(40, 40, '요청 초당 2,639건', 'b');
        s += arrow('dpc1', 'M40,74 L116,74', 'b', { svg: S });
        s += dots('dpc1', 'b', { n: 3, dur: 2.4 });
        s += tool(120, 54, 130, { label: '게이트웨이가 나눕니다', sub: '가중치 v417 99, v418 1' });
        s += arrow('dpc2', 'M252,66 C268,66 272,51 286,51', 'k', { svg: S });
        s += arrow('dpc3', 'M252,82 C268,82 272,97 286,97', 'k', { svg: S });
        s += dots('dpc2', 'k', { n: 2, dur: 2 }) + dots('dpc3', 'k', { n: 1, dur: 4 });
        s += box(290, 40, 112, 22, 'v417 파드 12대', 'k');
        s += box(290, 86, 112, 22, 'v418 파드 2대', 'k');
        s += T(408, 55, '요청 100건 중 99건', 'lbl sm');
        s += T(408, 101, '100건 중 1건', 'lbl b');
        s += T(40, 132, '가중치를 올리는 순서와 머무는 시간 (게이트를 지날 때마다)', 'lbl sm');
        const cols = [[40, 44, '1%', '5분', '초과율, 오류율', '새 파드 2대'], [84, 150, '10%', '30분', 'COPC, 클릭률', '2대'],
            [234, 150, '50%', '30분', '절반 부하', '6대'], [384, 96, '100%', '계속', '옛 파드 30분 더', '12대']];
        cols.forEach(c => {
            s += seg(c[0], 140, c[1], 22, c[2], 'track');
            const cx = c[0] + c[1] / 2;
            s += T(cx, 178, c[3], 'lbl k', 'middle');
            s += T(cx, 192, c[4], 'lbl sm', 'middle');
            s += T(cx, 206, c[5], 'lbl sm', 'middle');
        });
        [84, 234, 384].forEach(x => { s += tick(x, 140, 162); });
        s += tag(40, 224, '1% 는 죽지 않나만 봅니다. COPC 와 클릭률은 10% 에서 30분 뒤에 봅니다', 'k');
        s += lines(40, 250, ['50% 로 올리기 전에 파드를 6대로, 100% 에서 12대로. 옛 파드는 30분 더 둡니다']);
        s += T(40, 270, '가중치 한 줄로 1, 10, 50, 100 을 넓힙니다. 단계마다 확인하는 것이 다릅니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 3. 게이트 넷 — 넓혀도 되는지 정하는 문 ----------
    (function () {
        const S = 'dp-gates'; if (!has(S)) return; let s = '';
        s += T(40, 26, '게이트 넷. 값은 새 모델 무리에서 재고, 같은 시간 옛 무리와 비교합니다', 'lbl sm');
        s += T(40, 50, '게이트 (적어 둔 조건)', 'lbl sm');
        s += T(262, 50, '1% 단계 06:31', 'lbl sm');
        s += T(400, 50, '10% 단계 07:01', 'lbl sm');
        const rows = [
            ['8ms 초과율', '6% 이하 (평소 4.62%)', ['4.71% 통과', 'a'], ['통과', 'a']],
            ['오류율', '0.1% 이하', ['0.04% 통과', 'a'], ['통과', 'a']],
            ['COPC (실제 ÷ 예측)', '0.95 ~ 1.05', ['클릭 79건, 판정 안 함', 'c'], ['1.09 탈락', 'b']],
            ['클릭률 차이 (새 - 옛)', '-2% 이상', ['판정 안 함', 'c'], ['통과', 'a']],
        ];
        rows.forEach((r, i) => {
            const y = 58 + i * 44;
            s += list(40, y, 206, 36, [{ t: r[0], cls: 'h' }, r[1]]);
            s += tag(262, y + 9, r[2][0], r[2][1]);
            s += tag(400, y + 9, r[3][0], r[3][1]);
        });
        s += tag(40, 236, '하나라도 탈락이면 넓히지 않고 되돌립니다', 'b');
        s += tag(262, 236, 'COPC 는 클릭 1,600건이 모여야 읽습니다', 'k');
        s += T(40, 270, '앞의 둘은 서버가 멀쩡한가, 뒤의 둘은 모델이 돈을 버는가. 넷 다 열려야 지나갑니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 4. 롤백 시간선 — 알람부터 14분 ----------
    (function () {
        const S = 'dp-rollback'; if (!has(S)) return; let s = '';
        s += T(40, 22, '07:04 알람부터 07:18 확인까지 14분. 색은 그 시간을 누가 썼나입니다', 'lbl sm');
        s += T(228, 36, '명령 1분, 기계 1분', 'lbl sm', 'middle');
        // 14분을 440px 에 — 1분이 31.4px
        s += seg(40, 40, 157, 24, '사람 판단 5분', 'f-c');
        s += seg(197, 40, 31, 24, '', 'f-c');
        s += seg(228, 40, 32, 24, '', 'f-a');
        s += seg(260, 40, 220, 24, '확인 7분', 'f-c');
        s += tick(197, 40, 64);
        s += T(40, 80, '07:04', 'lbl k') + T(197, 80, '07:09', 'lbl k', 'middle') + T(228, 94, '07:10', 'lbl k', 'middle');
        s += T(260, 80, '07:11', 'lbl k', 'middle') + T(480, 80, '07:18', 'lbl k', 'end');
        s += tag(40, 112, '07:04 알람이 채널과 폰에 옵니다', 'b');
        s += tag(40, 138, '07:09 대시보드를 보고 되돌리기로 정합니다', 'c');
        s += tag(40, 164, '07:10 가중치 v418 을 0 으로. 명령 한 줄', 'a');
        s += tag(40, 190, '07:11 새 요청이 전부 v417 로 갑니다', 'a');
        s += tag(40, 216, '07:18 v418 파드 2대 내리고 평소 값 확인', 'k');
        s += list(300, 112, 200, 72, [{ t: '40분 동안 v418 이 답한 요청', cls: 'h' }, '633,360건', { t: '100% 로 올렸다면 6,333,600건', cls: 'b' }, '옛 파드가 떠 있어 초 단위입니다']);
        s += lines(300, 206, ['기계 1분, 사람 판단 5분, 확인 7분', '게이트를 미리 적어 두면 5분이 없어집니다'], 'lbl sm', 14);
        s += T(40, 270, '되돌리기는 파드를 끄는 일이 아니라 요청이 가는 길을 바꾸는 일입니다. 그래서 1분입니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 5. 웜업 — 새 파드의 첫 30초 ----------
    (function () {
        const S = 'dp-warmup'; if (!has(S)) return; let s = '';
        s += T(40, 26, '파드가 뜨는 순서 (초). 준비 신호를 언제 켜느냐가 첫 30초를 정합니다', 'lbl sm');
        const k = 440 / 75, x = t => Math.round((40 + t * k) * 10) / 10;
        // 웜업 없이 — 21초에 열고 30초를 느리게 받는다
        s += T(40, 46, '웜업 없이', 'lbl k');
        s += T(x(21), 46, '준비 신호 21초', 'lbl k', 'middle');
        s += seg(x(0), 52, x(12) - x(0), 20, '이미지 12초', 'f-c');
        s += seg(x(12), 52, x(18) - x(12), 20, '', 'f-c');
        s += seg(x(18), 52, x(21) - x(18), 20, '', 'f-c');
        s += seg(x(21), 52, x(51) - x(21), 20, '2.5배 느린 30초', 'f-b');
        s += seg(x(51), 52, 480 - x(51), 20, '4.62%', 'f-a');
        s += tick(x(12), 52, 72) + tick(x(18), 52, 72) + tick(x(21), 48, 76);
        s += T(x(6), 88, '12초', 'lbl sm', 'middle') + T(x(15), 88, '6초', 'lbl sm', 'middle') + T(x(19.5), 88, '3초', 'lbl sm', 'middle');
        s += T(x(36), 88, '초과율 11.74%', 'lbl b', 'middle') + T(x(63), 88, '그 뒤 4.62%', 'lbl sm', 'middle');
        // 웜업 200건 — 41초에 열고 처음부터 평소 속도
        s += T(40, 126, '웜업 200건', 'lbl k');
        s += T(x(41), 126, '준비 신호 41초', 'lbl k', 'middle');
        s += seg(x(0), 132, x(12) - x(0), 20, '이미지 12초', 'f-c');
        s += seg(x(12), 132, x(18) - x(12), 20, '', 'f-c');
        s += seg(x(18), 132, x(21) - x(18), 20, '', 'f-c');
        s += seg(x(21), 132, x(41) - x(21), 20, '웜업 20초', 'f-c');
        s += seg(x(41), 132, 480 - x(41), 20, '처음부터 4.62%', 'f-a');
        s += tick(x(12), 132, 152) + tick(x(18), 132, 152) + tick(x(21), 132, 152) + tick(x(41), 128, 156);
        s += T(x(6), 168, '12초', 'lbl sm', 'middle') + T(x(15), 168, '6초', 'lbl sm', 'middle') + T(x(19.5), 168, '3초', 'lbl sm', 'middle');
        s += T(x(31), 168, '가짜 요청 200건', 'lbl sm', 'middle') + T(x(58), 168, '초과율 4.62%', 'lbl sm', 'middle');
        s += tag(40, 190, '1% 단계라면 느린 30초에 요청 792건이 걸립니다', 'k');
        s += tag(40, 216, '게이트가 그 30초를 포함해 재면 멀쩡한 모델도 첫 문에서 걸립니다', 'b');
        s += lines(40, 248, ['06:26 의 1% 단계에서 초과율이 4.71% 로 평소와 같았던 이유가 이 20초입니다']);
        s += T(40, 270, '준비 신호를 웜업 뒤로 20초 미루면 느린 30초가 사라집니다. 모델이 아니라 절차의 문제입니다', 'lbl');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
