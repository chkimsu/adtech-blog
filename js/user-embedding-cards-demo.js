/**
 * user-embedding-cards-demo.js — LLM 유저 임베딩 카드 네 장
 *
 * 회원의 30일 문서를 새벽에 64차원 벡터로 바꿔 피처 스토어에 두고, pCTR 랭커가 요청 때 그 벡터를 피처로 읽는 자리를 카드 한 장씩으로 그린다.
 * 새벽 배치, 피처 스토어의 키와 벡터, 랭커가 읽는 피처, 예산 8ms 와 실시간 호출.
 * 색은 css/style.css 의 카드 부품 블록이 토큰으로 정한다. 파랑은 놓여 있는 데이터(문서, 벡터, 피처 스토어), 벽돌색은 지금 오는 것
 * (요청, 코사인, LLM 호출), 먹색은 모델과 서버, 회색은 만드는 작업(새벽 배치)과 비교할 기준값이고, 점선은 적어 둔 것(낱말마다 인코더가 정한 버킷)이다.
 *
 * 숫자는 전부 llm-user-embedding-features 글의 파이썬 블록 셋이 찍은 출력에서 옮긴 값이다. 회원, 광고, 가짜 클릭은 가상 값이고,
 * LLM 호출의 토큰과 시간은 data/llm-records/llm-first-call.json 의 기록이다. 글의 블록을 고치면 여기도 고친다.
 *
 * ?card=key 가 붙으면 그 카드만 남긴다 (글 안에 iframe 으로 넣을 때 쓴다).
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, box, tag, tool, list, arrow, svg, table, db, srv } = window.CardKit;
    const has = id => !!document.getElementById(id);
    // 눈금 상자 안에 n / max 만큼 채운 막대. n 이 0 이하면 채우지 않는다
    const bar = (x, y, w, n, max, cls, h = 12) =>
        `<rect class="track" x="${x}" y="${y}" width="${w}" height="${h}"/>` +
        (n > 0 ? `<rect class="f-${cls}" x="${x}" y="${y}" width="${Math.max(2, Math.round(w * n / max))}" height="${h}"/>` : '');

    // ---------- 1. 새벽 배치 ----------
    (function () {
        const S = 'ue-batch'; if (!has(S)) return; let s = '';
        s += T(40, 20, '새벽 04:30 에 회원 2,000명의 문서를 한 번에 벡터로 바꿉니다', 'lbl sm');
        s += table(40, 36, { label: '문서 2,000편' });
        s += arrow('ue-batch-in', 'M104,58 L148,58', 'k', { svg: S });
        s += tool(152, 38, 196, { label: '장난감 인코더', sub: 'crc32 로 버킷 64개, 길이 1', clock: true });
        s += arrow('ue-batch-out', 'M352,58 L404,58', 'k', { svg: S });
        s += db(440, 44, { label: '피처 스토어' });
        s += list(40, 116, 450, 78, [{ t: '회원 A 의 낱말과 횟수 → 버킷 번호 (벡터의 값)', cls: 'h' }]);
        // [낱말과 횟수, 버킷, 값] 블록 1 의 3단계와 4단계가 찍은 줄
        const rows = [['러닝화 12번', 25, 0.676], ['러닝글 9번', 2, 0.507], ['운동앱 8번', 54, 0.451],
            ['여행글 4번', 24, 0.225], ['카페글 3번', 44, 0.169], ['운동용품구매 1번', 57, 0.056]];
        rows.forEach(([word, slot, v], i) => {
            const x = i % 2 ? 270 : 49, y = 146 + Math.floor(i / 2) * 16;
            s += T(x, y, `${word} → ${slot}번 (${v.toFixed(3)})`, 'list-t');
        });
        s += T(40, 216, '낱말 126종이 버킷 64개 가운데 56개에, 두 낱말 이상 든 버킷 40개', 'lbl k');
        s += T(40, 238, '러닝화는 25번, 런닝화는 35번: 뜻이 같아도 장난감에게는 다른 낱말', 'lbl');
        s += T(40, 260, '1,400만 명 × 64차원 × 4바이트 = 3,584,000,000바이트 = 3.58GB', 'lbl');
        s += T(40, 284, '학습한 인코더라면 행동이 비슷한 회원에게 가까운 벡터를 줍니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 2. 피처 스토어의 키와 벡터 ----------
    (function () {
        const S = 'ue-store'; if (!has(S)) return; let s = '';
        // 벡터의 값 64개를 칸 64개로 그린다. 0 이 아닌 값만 그 크기만큼 아래에서부터 채운다
        const strip = (y, vals) => {
            let r = '';
            for (let j = 0; j < 64; j++) {
                r += `<rect class="track" x="${104 + j * 5}" y="${y}" width="5" height="18"/>`;
                if (vals[j]) {
                    const h = Math.max(2, Math.round(18 * vals[j]));
                    r += `<rect class="f-a" x="${104 + j * 5}" y="${y + 18 - h}" width="5" height="${h}"/>`;
                }
            }
            return r;
        };
        s += T(40, 20, '키는 회원 번호이고, 값은 64차원 벡터와 만든 시각입니다', 'lbl sm');
        s += T(40, 44, '키', 'lbl k');
        s += T(104, 44, '값: 벡터의 값 64개 (0 이 아닌 값만 채움)', 'lbl k');
        s += T(490, 44, '만든 시각', 'lbl k', 'end');
        // 회원 A 는 블록 1 의 4단계가 찍은 값이다
        s += T(40, 68, '0 (회원 A)', 'lbl');
        s += strip(55, { 2: 0.507, 24: 0.225, 25: 0.676, 44: 0.169, 54: 0.451, 57: 0.056 });
        s += T(490, 68, '04:30', 'lbl', 'end');
        // 회원 B 는 블록 1 이 찍은 낱말 횟수(15, 2, 2, 1, 1)와 버킷으로 그린 모양이다
        const nb = Math.sqrt(15 * 15 + 2 * 2 + 2 * 2 + 1 + 1);
        s += T(40, 96, '1 (회원 B)', 'lbl');
        s += strip(83, { 11: 15 / nb, 38: 2 / nb, 53: 2 / nb, 14: 1 / nb, 8: 1 / nb });
        s += T(490, 96, '04:30', 'lbl', 'end');
        s += T(40, 120, '… 회원 1,999번까지 키 2,000개', 'lbl sm');
        s += `<line class="split" x1="40" y1="134" x2="490" y2="134"/>`;
        s += T(40, 156, '회원 A 의 0 이 아닌 값: 2번 0.507, 24번 0.225, 25번 0.676,', 'lbl');
        s += T(40, 174, '44번 0.169, 54번 0.451, 57번 0.056', 'lbl');
        s += T(40, 196, '회원 B 의 버킷: 캠핑글 11번, 버너 38번, 텐트 53번, 캠핑테이블 14번, 침낭 8번', 'lbl sm');
        s += T(40, 218, '같이 쓰는 버킷이 없어 회원 A 와 B 의 코사인은 0.000', 'lbl k');
        s += box(40, 236, 120, 22, '요청: 회원 0', 'b', 10);
        s += arrow('ue-store-read', 'M164,247 L216,247', 'b', { svg: S });
        s += box(220, 236, 130, 22, '키로 읽기 한 번', 'a', 10);
        s += T(362, 251, '인코더는 부르지 않음', 'lbl sm');
        s += T(40, 286, '회원 1,400만 명이면 3,584,000,000바이트 = 3.58GB', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 3. 랭커가 읽는 피처 ----------
    (function () {
        const S = 'ue-ranker'; if (!has(S)) return; let s = '';
        s += T(40, 20, '랭커는 피처 넷으로 클릭 확률 pCTR 을 매깁니다', 'lbl sm');
        // [피처, 색] 앞의 셋이 기본 피처, 마지막이 요청 때 두 벡터로 계산하는 코사인
        [['광고 (러닝화, 여행사, 카페)', 'a'], ['세그먼트 317', 'a'], ['30일 활동량', 'a'], ['코사인 (유저 벡터, 광고 벡터)', 'b']]
            .forEach(([t, c], i) => { s += box(40, 32 + i * 26, 200, 20, t, c, 10); });
        s += arrow('ue-ranker-in', 'M244,77 L296,77', 'k', { svg: S });
        s += srv(300, 46, { label: '랭커', sub: '로지스틱 회귀' });
        s += arrow('ue-ranker-out', 'M350,73 L398,73', 'k', { svg: S });
        s += tag(402, 64, 'pCTR', 'k');
        s += T(40, 154, '시험 회원 400명의 AUC (막대는 0.5 에서 시작)', 'lbl k');
        // [모델, AUC, 색] 블록 2 의 5단계가 찍은 값
        [['평균 CTR 하나', 0.500, 'c'], ['기본 피처 셋', 0.637, 'a'], ['기본 + 코사인', 0.670, 'b'], ['숨은 관심 그대로', 0.738, 'c']]
            .forEach(([name, v, cls], i) => {
                const y = 162 + i * 20;
                s += T(40, y + 11, name, cls === 'b' ? 'lbl k' : 'lbl');
                s += bar(150, y + 1, 260, v - 0.5, 0.25, cls, 12);
                s += T(490, y + 11, v.toFixed(3), cls === 'b' ? 'lbl k' : 'lbl', 'end');
            });
        s += T(40, 260, '광고 하나 안의 AUC: 러닝화 0.555 → 0.611, 여행사 0.577 → 0.649', 'lbl sm');
        s += T(40, 276, '카페 0.574 → 0.627. 여행사와 카페의 관심은 코사인만 직접 알려 줍니다', 'lbl sm');
        s += T(40, 294, '시험 logloss 0.0766 → 0.0756 (평균 CTR 하나 0.0783)', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 4. 예산 8ms 와 실시간 호출 ----------
    (function () {
        const S = 'ue-budget'; if (!has(S)) return; let s = '';
        const W = 450;                                // 1,114ms 막대의 폭
        s += T(40, 20, 'LLM 호출 한 번과 모델 서버 예산 8ms 를 같은 눈금에 놓습니다', 'lbl sm');
        s += `<rect class="f-b" x="40" y="30" width="${W}" height="20"/>`;
        s += `<rect class="f-k" x="40" y="30" width="${Math.max(2, Math.round(W * 8 / 1114))}" height="20"/>`;
        s += T(40, 66, '예산 8ms (왼쪽 끝의 먹색)', 'lbl k');
        s += T(490, 66, 'thinking 을 끈 호출 1,114ms', 'lbl', 'end');
        s += T(40, 86, '1,114ms 는 예산의 139배, thinking 을 켠 31,979ms 는 3,997배', 'lbl');
        s += `<line class="split" x1="40" y1="100" x2="490" y2="100"/>`;
        s += T(40, 122, '하루 값 (상용 모델은 가상 단가, 짧은 호출로 센 하한)', 'lbl k');
        // [방식, 하루 원, 색] 블록 3 의 2단계와 3단계가 찍은 값
        [['노출마다 큰 상용 모델', 98496000, 'b'], ['노출마다 작은 상용 모델', 9302400, 'b'], ['새벽 배치, GPU 한 대', 6425, 'c']]
            .forEach(([name, v, cls], i) => {
                const y = 132 + i * 24;
                s += T(40, y + 11, name, cls === 'c' ? 'lbl k' : 'lbl');
                s += bar(190, y + 1, 180, v, 98496000, cls);
                s += T(490, y + 11, `${v.toLocaleString('ko-KR')}원`, cls === 'c' ? 'lbl k' : 'lbl', 'end');
            });
        s += T(40, 222, '하루 값은 새벽 배치의 1,448배(작은 상용)와 15,330배(큰 상용)', 'lbl');
        s += T(40, 244, '하루 횟수: 노출마다 2억 2,800만 번, 새벽 배치는 1,400만 명에 한 번씩', 'lbl');
        s += T(40, 266, '새벽 배치는 1초에 2,300명, 시간당 3,800원으로 1.69시간', 'lbl sm');
        s += T(40, 286, '랭커는 요청 때 피처 스토어의 벡터를 읽기만 합니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
