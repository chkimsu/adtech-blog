/**
 * causal-cards-demo.js — 인과추론 카드 네 장
 *
 * 「광고가 진짜 만든 차이」를 재는 네 방법을 카드 한 장씩으로. 네 방법 모두 그림으로 보면 한눈에 든다.
 * 이중차분은 나란히 가던 두 선 중 하나가 꺾이는 높이, 회귀 불연속은 컷에서의 점프 높이,
 * 도구변수는 배정 효과를 순응률로 나눈 값, 랜덤 실험은 두 무리가 저절로 같아지는 것이다.
 * 색은 css/style.css 의 카드 부품 블록이 정한다 — 파랑 처치와 결론, 회색 대조와 견주는 값,
 * 벽돌색 틀린 값과 착시. 숫자는 전부 그 글의 가상 데이터 값이다.
 *
 * 호스트(#mc-<key>)가 없는 카드는 건너뛴다. ?card=key 가 붙으면 그 카드만 남긴다.
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, tag, table, tool, list, arrow, dots, svg, hbar, lines } = window.CardKit;
    const has = id => !!document.getElementById(id);
    const dot = (x, y, cls) => `<circle class="dot ${cls}" cx="${x}" cy="${y}" r="3"/>`;
    const line = (x1, y1, x2, y2, cls) => `<line class="${cls}" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`;

    // ---------- 1. 이중차분 (difference-in-differences) ----------
    (function () {
        const S = 'mc-did'; if (!has(S)) return; let s = '';
        s += T(40, 26, '두 지역의 월 매출 (억원). 5월에 서울과 경기에만 광고를 켰습니다', 'lbl sm');
        s += line(288, 46, 288, 196, 'split');
        s += T(292, 42, '광고 시작', 'lbl sm');
        // 처치지역 — 4월까지 대조와 나란히, 5월에 꺾인다
        s += `<path class="ar a" d="M60,144 L125,128 L190,120 L255,109 L320,70"/>`;
        s += `<path class="ar a dash" d="M255,109 L320,101"/>`;
        [[60, 144], [125, 128], [190, 120], [255, 109], [320, 70]].forEach(p => { s += dot(p[0], p[1], 'a'); });
        // 대조지역
        s += `<path class="ar c" d="M60,180 L125,171 L190,160 L255,149 L320,141"/>`;
        [[60, 180], [125, 171], [190, 160], [255, 149], [320, 141]].forEach(p => { s += dot(p[0], p[1], 'c'); });
        s += '<rect class="f-a" x="40" y="38" width="10" height="10"/>' + T(56, 47, '처치지역 (서울과 경기)', 'lbl k');
        s += '<rect class="f-c" x="40" y="56" width="10" height="10"/>' + T(56, 65, '대조지역 (나머지 지역)', 'lbl sm');
        s += T(320, 58, '130.10', 'lbl k', 'middle');
        s += T(326, 106, '114.69 — 광고가 없었다면', 'lbl sm');
        s += `<path class="ar b" d="M332,70 L332,100"/>`;
        s += T(338, 88, '+15.40억', 'lbl b');
        ['1월', '2월', '3월', '4월', '5월'].forEach((m, i) => { s += T(60 + i * 65, 214, m, 'lbl sm', 'middle'); });
        s += tag(40, 232, '단순 전후비교 +19.79억', 'c');
        s += tag(240, 232, '단순 지역비교 +35.36억', 'c');
        s += tag(40, 258, '이중차분 +15.40억 — 참값 15억', 'a');
        s += T(40, 296, '두 지역이 나란히 움직이던 것이 근거입니다. 4월까지 격차는 18억에서 22억 사이였습니다', 'lbl');
        svg(S, s, 330);
    })();

    // ---------- 2. 회귀 불연속 (regression-discontinuity) ----------
    (function () {
        const S = 'mc-rdd'; if (!has(S)) return; let s = '';
        s += T(40, 26, '품질점수 구간별 평균 CTR. 7.00점을 넘으면 프리미엄 지면을 받습니다', 'lbl sm');
        s += line(239, 44, 239, 192, 'split');
        s += T(243, 40, '컷오프 7.00', 'lbl k');
        s += `<path class="ar c" d="M88,176 L221,170"/>`;
        s += `<path class="ar a" d="M257,86 L432,78"/>`;
        [[91, 175], [133, 172], [175, 172], [218, 170]].forEach(p => { s += dot(p[0], p[1], 'c'); });
        [[260, 85], [302, 84], [344, 82], [387, 79], [429, 78]].forEach(p => { s += dot(p[0], p[1], 'a'); });
        s += `<path class="ar b" d="M239,168 L239,88"/>`;
        s += T(246, 132, '점프 0.65%p', 'lbl b');
        s += T(214, 188, '1.98%', 'lbl k', 'end');
        s += T(264, 76, '2.63%', 'lbl k');
        s += T(91, 204, '6.80', 'lbl sm', 'middle');
        s += T(239, 204, '7.00', 'lbl sm', 'middle');
        s += T(429, 204, '7.25', 'lbl sm', 'middle');
        s += T(40, 228, '컷 양옆은 점수가 0.05 차이인데 CTR 은 1.98%에서 2.63%로 뜁니다', 'lbl sm');
        s += tag(40, 238, '멀리 떨어진 구간끼리 비교하면 2.80%p — 실력 차이가 섞입니다', 'b');
        s += T(40, 274, '창을 ±0.05 에서 ±3.00 으로 넓히면 단순 평균차의 편향이 0.05%p 에서 1.20%p 로 커집니다', 'lbl sm');
        s += T(40, 292, '양옆 직선을 먼저 걷어내면 어느 창에서든 0.01%p 근처에 머뭅니다', 'lbl sm');
        s += T(40, 322, '효과는 컷에서의 점프 높이입니다. 멀리 보면 실력이 섞이고 좁게 보면 흔들립니다', 'lbl');
        svg(S, s, 350);
    })();

    // ---------- 3. 도구변수 (instrumental-variables) ----------
    (function () {
        const S = 'mc-iv'; if (!has(S)) return; let s = '';
        s += T(40, 26, '캠페인 대상 20만 명을 무작위로 둘로 나눕니다', 'lbl sm');
        s += table(40, 40, { label: '배정군 10만 명' });
        s += tool(160, 46, 130, { label: '실제로 열어 본 사람', sub: '4만 명, 나머지 6만은 미노출' });
        s += arrow('iv1', 'M98,62 L156,62', 'b', { svg: S });
        s += arrow('iv3', 'M292,64 L326,60', 'b', { svg: S });
        s += dots('iv1', 'b', { n: 2, dur: 2.2 }) + dots('iv3', 'b', { n: 1, dur: 1.8 });
        s += tag(330, 52, '전환율 3.00%', 'a');
        s += list(160, 112, 170, 44, [{ t: '순응률 40%', cls: 'h' }, '배정 10만 중 실제 노출 4만']);
        s += table(40, 150, { label: '대조군 10만 명' });
        s += tag(330, 160, '전환율 2.00%', 'c');
        s += arrow('iv2', 'M98,172 C200,180 280,174 326,170', 'c', { svg: S });
        s += dots('iv2', 'c', { n: 2, dur: 2.6 });
        s += T(40, 244, 'ITT = 3.00% − 2.00% = +1.00%p 를 순응률 0.40 으로 나눕니다', 'lbl k');
        s += tag(40, 254, 'LATE +2.50%p — 실제로 본 사람에게 준 효과', 'a');
        s += tag(340, 254, 'naive 비교 +3.13%p', 'b');
        s += T(40, 300, '배정은 무작위라 도구로 쓸 수 있습니다. 배정 효과를 순응률로 나누면 노출 효과가 나옵니다', 'lbl');
        svg(S, s, 330);
    })();

    // ---------- 4. 랜덤 실험 (rct-randomized-experiment) ----------
    (function () {
        const S = 'mc-rct'; if (!has(S)) return; let s = '';
        s += T(40, 26, '유저 10만 명을 동전으로 나누면', 'lbl sm');
        s += table(40, 40, { label: '처치군 50,285명' });
        s += table(40, 130, { label: '대조군 49,715명' });
        s += tool(140, 82, 92, { label: '무작위 배정' });
        s += arrow('rc1', 'M98,66 C118,66 126,82 136,88', 'a', { svg: S });
        s += arrow('rc2', 'M98,152 C118,152 126,122 136,116', 'a', { svg: S });
        s += dots('rc1', 'a', { n: 1, dur: 2.2 }) + dots('rc2', 'a', { n: 1, dur: 2.2 });
        s += list(250, 40, 242, 72, [{ t: '평균 연령   34.13세 대 34.06세', cls: 'h' }, '앱 사용시간   42.09분 대 41.97분', '여성 비율   54.9% 대 55.2%']);
        s += list(250, 124, 242, 30, [{ t: '관측 안 되는 구매 의향   49.75 대 50.02', cls: 'b' }]);
        s += T(250, 170, '이름도 모르는 특성까지 같아집니다', 'lbl k');
        s += T(40, 214, '잡으려는 리프트가 작을수록 필요한 사람이 제곱으로 늡니다 (기저 전환율 2.0%)', 'lbl sm');
        [['+20%', 21106 / 315207, '21,106명'], ['+10%', 80680 / 315207, '80,680명'], ['+5%', 1, '315,207명']].forEach((r, i) => {
            const y = 226 + i * 26;
            s += T(40, y + 11, r[0], 'lbl k');
            s += hbar(150, y, 290, r[1], 'a');
            s += T(448, y + 11, r[2], 'lbl k');
        });
        s += T(40, 326, '표본을 반으로 줄이면 검출력이 80.5%에서 50.8%로 떨어집니다. 차이가 없어도 5.1%는 유의하다고 나옵니다', 'lbl');
        svg(S, s, 350);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
