/**
 * window-cards-demo.js — 스트림 집계 카드 네 장
 *
 * 「광고별 최근 1시간 클릭 수」 하나가 세어지는 자리 하나가 카드 한 장. 점이 흐르는 방향이 데이터가 가는 방향이다.
 * 색은 css/style.css 의 카드 부품 블록이 정한다 — 파랑 놓여 있는 데이터(topic, Redis 값, 아카이브), 벽돌색 지금 오는 것(클릭),
 * 먹색 서버(광고 서버), 회색 만드는 작업(창 집계, 배치). 점선 상자는 적어 둔 것(창 설정, 워터마크).
 * 숫자는 전부 스트림 집계 글(stream-window-aggregation)의 가상 값이다 — 광고 9931 의 14:00~15:00 클릭이 스트림 1,203, 배치 1,204,
 * 클릭 도착은 5초 안 95%, 2분 안 99.9%, 2분 넘게 늦는 것이 하루 2,280건.
 *
 * 호스트(#wd-<key>)가 없는 카드는 건너뛴다. ?card=key 가 붙으면 그 카드만 남긴다 (글 안에 iframe 으로 넣을 때 쓴다).
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, box, tag, srv, table, db, tool, user, arrow, dots, svg, ruler, lines } = window.CardKit;
    const has = id => !!document.getElementById(id);

    // ---------- 1. 텀블링 창과 슬라이딩 창 ----------
    (function () {
        const S = 'wd-windows'; if (!has(S)) return; let s = '';
        // 시간선: 13:30 부터 15:30 까지, 1분이 3.5px
        const X = m => 60 + (m - 810) * 3.5;                    // m 은 0시부터 센 분
        s += T(40, 26, '요청 15:07 에 어느 창의 값을 읽나', 'lbl sm');
        s += T(X(907), 26, '요청 15:07', 'lbl b', 'middle');
        s += ruler(60, 46, 420, [[X(840), '14:00', ''], [X(900), '15:00', '']], { h: 8 });
        s += `<line class="ar b" x1="${X(907)}" y1="34" x2="${X(907)}" y2="190"/>`;
        // 텀블링 1시간
        s += T(40, 72, '텀블링 1시간', 'lbl k');
        s += `<rect class="track" x="60" y="78" width="${X(840) - 60}" height="20"/>`;
        s += box(X(840), 78, X(900) - X(840), 20, '14:00~15:00', 'a', 10);
        s += `<rect class="list" x="${X(900)}" y="78" width="${480 - X(900)}" height="20"/>`;
        s += T(X(907) + 5, 92, '아직 안 닫힘', 'lbl sm');
        s += tag(150, 106, '15:07 요청은 14:00~15:00 값. 7분 묵음', 'b');
        // 슬라이딩 60분, 1분마다 — 창이 1분씩 밀려 겹친다
        s += T(40, 164, '슬라이딩 60분, 1분마다', 'lbl k');
        for (let i = 0; i < 4; i++) s += `<rect class="track" x="${X(842 + i)}" y="${142 + i * 5}" width="210" height="20"/>`;
        s += box(X(846), 162, 210, 20, '14:06~15:06', 'a', 10);
        s += tag(150, 190, '15:07 요청은 14:06~15:06 값. 1분 묵음', 'a');
        s += lines(40, 228, ['텀블링은 15:59 요청도 14:00~15:00 을 봅니다. 최대 60분 묵습니다', '슬라이딩은 1분 조각 60개를 더해 늘 1분 안의 값을 냅니다'], 'lbl sm', 14);
        s += T(40, 270, '같은 요청 15:07 에 텀블링은 14:00~15:00, 슬라이딩은 14:06~15:06 을 줍니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 2. 워터마크 — 이벤트 시각과 도착 시각 ----------
    (function () {
        const S = 'wd-watermark'; if (!has(S)) return; let s = '';
        // 14:53 부터 15:07 까지, 1분이 30px
        const X = m => 60 + (m - 893) * 30;
        s += T(40, 26, '클릭이 일어난 시각 (이벤트 시각)', 'lbl sm');
        s += box(60, 58, X(900) - 60, 22, '창 14:00~15:00 (앞은 생략)', 'a', 10);
        s += `<rect class="list" x="${X(900)}" y="58" width="${480 - X(900)}" height="22"/>`;
        s += T(X(900) + 6, 73, '15:00~16:00', 'lbl sm');
        s += T(40, 130, '잡에 도착한 시각', 'lbl sm');
        s += ruler(60, 140, 420, [[X(900), '', '15:00'], [X(902), '', '15:02'], [X(905), '', '15:05']], { h: 6 });
        // 클릭 셋 — 일어난 시각에서 도착한 시각으로 내려간다. C 는 12초, A 는 12초, B 는 219초 뒤에 도착한다
        const C = X(895 + 10 / 60), Carr = X(895 + 22 / 60);
        const A = X(899 + 50 / 60), Aarr = X(900 + 2 / 60);
        const B = X(899 + 31 / 60), Barr = X(903 + 10 / 60);
        s += arrow('wm1', `M${C},82 L${Carr},136`, 'a', { svg: S });
        s += arrow('wm2', `M${A},82 L${Aarr},136`, 'a', { svg: S });
        s += arrow('wm3', `M${B},82 L${Barr},136`, 'b', { svg: S });
        s += dots('wm1', 'a', { n: 1, dur: 2.2 }) + dots('wm2', 'a', { n: 1, dur: 2.2 }) + dots('wm3', 'b', { n: 1, dur: 3 });
        s += T(C - 5, 96, 'C 14:55:10', 'lbl k', 'end') + T(A + 5, 96, 'A 14:59:50', 'lbl k');
        s += T(B - 5, 112, 'B 14:59:31', 'lbl b', 'end');
        s += T(Aarr + 6, 128, 'A 12초 뒤', 'lbl sm');
        // 워터마크 — 창 끝 15:00 에서 2분 뒤에 닫는다
        s += `<line class="ar b dash" x1="${X(902)}" y1="100" x2="${X(902)}" y2="172"/>`;
        s += T(X(902) - 6, 184, '창 닫힘 15:02 = 끝 15:00 + 워터마크 2분', 'lbl b', 'end');
        s += tag(283, 194, 'B 219초 뒤 도착. 닫힌 뒤라 빠집니다', 'b');
        s += lines(40, 220, ['도착 지연: 5초 안 95%', '2분 안 99.9%', '2분 넘음 0.1% (하루 2,280건)'], 'lbl sm', 13);
        s += T(40, 270, '창은 끝나고 2분 뒤에 닫힙니다. 그 뒤에 온 0.1% 는 이 창에 들어가지 않습니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 3. 늦게 온 클릭은 어디로 ----------
    (function () {
        const S = 'wd-late'; if (!has(S)) return; let s = '';
        s += user(60, 44, '회원 A');
        s += tag(40, 96, '클릭 14:59:31', 'b');
        s += T(40, 130, '도착 15:03:10', 'lbl b');
        s += T(40, 144, '창은 15:02 에 이미 닫힘', 'lbl sm');
        s += tool(170, 56, 120, { label: '창 집계', sub: '14:00~15:00 닫힘', clock: true });
        s += arrow('lt1', 'M84,70 L166,74', 'b', { svg: S });
        s += dots('lt1', 'b', { n: 1, dur: 2 });
        // 갈래 셋
        s += arrow('lt2', 'M290,68 C310,68 316,44 326,44', 'c', { svg: S, dash: true });
        s += arrow('lt3', 'M290,76 C310,76 316,118 326,118', 'a', { svg: S });
        s += arrow('lt4', 'M290,84 C310,84 316,200 344,200', 'k', { svg: S, dash: true });
        s += dots('lt3', 'a', { n: 1, dur: 2.4 }) + dots('lt4', 'k', { n: 1, dur: 2.4 });
        s += tag(330, 34, '① 버립니다', 'c');
        s += T(330, 66, '값 1,203 그대로. 비용 0', 'lbl sm');
        s += table(330, 96, { label: 'ad.click.late' });
        s += T(396, 108, '② 따로 보관합니다', 'lbl k');
        s += T(396, 122, '검산에 씁니다', 'lbl sm');
        s += db(350, 186, { label: 'Redis 값' });
        s += tag(396, 184, '③ 다시 셉니다', 'k');
        s += T(396, 218, '1,203 → 1,204 로 고쳐 씁니다', 'lbl sm');
        s += T(396, 232, '창을 30분 더 열어 둡니다', 'lbl sm');
        s += lines(40, 200, ['서빙 피처는 ① 과 ② 입니다', '학습 데이터는 하루 뒤 배치가 다 셉니다'], 'lbl sm', 14);
        s += T(40, 270, '서빙 피처는 버리고 따로 보관합니다. 다시 세면 상태와 쓰기가 늘어납니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 4. 같은 시간을 두 번 센다 — 배치와 스트림 ----------
    (function () {
        const S = 'wd-batchvs'; if (!has(S)) return; let s = '';
        s += table(40, 40, { label: 'topic ad.click' });
        // 위: 스트림 잡이 그 시각에 세어 Redis 에 두고 광고 서버가 읽는다
        s += tool(150, 46, 96, { label: '스트림 잡', sub: '그 시각에 셉니다' });
        s += arrow('bv1', 'M98,62 L146,66', 'b', { svg: S });
        s += db(300, 52, { label: 'Redis' });
        s += arrow('bv2', 'M246,66 L280,60', 'a', { svg: S });
        s += tag(330, 18, 'ad:9931:clk_1h = 1,203', 'a');
        s += srv(440, 44, { cls: 'k', label: '광고 서버' });
        s += arrow('bv3', 'M320,76 C360,90 400,72 436,72', 'k', { svg: S, dash: true });
        s += dots('bv1', 'b', { n: 2, dur: 2 }) + dots('bv2', 'a', { n: 1, dur: 1.8 }) + dots('bv3', 'k', { n: 1, dur: 2.2 });
        // 아래: 아카이브를 하루 뒤 배치가 다 세어 학습 데이터로
        s += table(150, 150, { label: '아카이브 (하루 뒤)' });
        s += arrow('bv4', 'M68,128 C68,160 110,170 146,172', 'a', { svg: S, dash: true });
        s += tool(250, 156, 96, { label: '배치', sub: '다 모아서 셉니다', clock: true });
        s += arrow('bv5', 'M206,178 L246,176', 'a', { svg: S });
        s += table(380, 150, { label: '학습 데이터', sub: '1,204' });
        s += arrow('bv6', 'M346,176 L376,176', 'a', { svg: S });
        s += dots('bv4', 'a', { n: 1, dur: 3 }) + dots('bv5', 'a', { n: 1, dur: 1.8 }) + dots('bv6', 'a', { n: 1, dur: 1.8 });
        s += tag(150, 224, '차이 1건 = 늦게 온 클릭', 'b');
        s += T(150, 252, '서빙은 1,203 을 봤고 학습은 1,204 를 배웁니다', 'lbl sm');
        s += T(40, 270, '학습과 서빙이 같은 값을 보게 하려면 서빙이 본 값을 로그로 남깁니다', 'lbl');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
