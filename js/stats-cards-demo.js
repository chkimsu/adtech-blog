/**
 * stats-cards-demo.js — 통계 카드 여섯 장
 *
 * 신뢰구간과 t 검정 글(stats-confidence-interval-ttest)의 개념 하나가 카드 한 장이다.
 * 왼쪽에 잰 값, 가운데에 흔들림을 재는 계산, 오른쪽에 판정이다.
 * 색은 css/style.css 의 카드 부품 블록이 정한다 — 이 데크만 뜻이 다르다.
 *   파랑(f-a) 잰 값, 벽돌색(f-b) 참값과 문턱, 먹색(f-k) 결론, 회색(tool) 흔들림을 재는 계산.
 * 숫자는 전부 그 글의 가상 값이고, 시뮬레이션 값은 시드 9 로 직접 돌려 나온 것이다.
 *
 * 호스트(#st-<key>)가 없는 카드는 건너뛴다. ?card=key 가 붙으면 그 카드만 남긴다.
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, tw, tag, tool, svg, hbar, ruler, lines } = window.CardKit;
    const has = id => !!document.getElementById(id);
    // 클릭률(%)을 가로 좌표로. 카드 1, 2 가 같은 자를 쓴다 — 1.00% 가 60, 1.40% 가 470
    const X1 = v => 60 + (v - 1.00) * 1025;
    // 세로 선 — 참값과 문턱. 상자보다 먼저 그리면 상자 뒤로 지나간다
    const vbar = (x, y, h, cls) => `<rect class="f-${cls}" x="${(x - 0.9).toFixed(1)}" y="${y}" width="1.8" height="${h}"/>`;
    // 가운데를 맞춘 라벨 상자
    const ctag = (cx, y, txt, cls) => tag(cx - (tw(txt) + 14) / 2, y, txt, cls);

    // ---------- 1. 잰 값은 흔들린다 ----------
    (function () {
        const S = 'st-sample'; if (!has(S)) return; let s = '';
        s += T(40, 22, '소재 B 를 노출 40,000 씩 다섯 번 재 봤습니다', 'lbl sm');
        s += vbar(X1(1.21), 44, 144, 'b');
        s += T(X1(1.21), 38, '참 클릭률 1.21%', 'lbl b', 'middle');
        ['1.30%', '1.28%', '1.20%', '1.15%', '1.26%'].forEach((v, i) => {
            const y = 46 + i * 22;
            s += T(40, y + 13, (i + 1) + '번째', 'lbl sm');
            s += ctag(X1(parseFloat(v)), y, v, 'a');
        });
        s += ruler(60, 188, 410, [[60, '', '1.00%'], [X1(1.10), '', '1.10%'], [X1(1.20), '', '1.20%'], [X1(1.30), '', '1.30%'], [470, '', '1.40%']], { h: 12 });
        s += T(40, 242, '참 클릭률은 하나인데 40,000 을 뽑을 때마다 다른 값이 나옵니다', 'lbl sm');
        s += T(40, 270, '같은 소재인데 잰 값이 1.15% 에서 1.30% 까지 흩어집니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 2. 표준오차 — 표본이 4배면 폭이 절반 ----------
    (function () {
        const S = 'st-se'; if (!has(S)) return; let s = '';
        s += T(40, 22, '잰 값 1.21% 를 가운데 두고 구간을 그렸습니다', 'lbl sm');
        s += vbar(X1(1.21), 44, 132, 'b');
        s += T(X1(1.21), 38, '1.21%', 'lbl b', 'middle');
        s += T(40, 70, '노출 40,000', 'lbl k');
        s += `<rect class="f-a" x="${X1(1.103).toFixed(1)}" y="58" width="${(X1(1.317) - X1(1.103)).toFixed(1)}" height="16"/>`;
        s += T(X1(1.317) + 8, 70, '한쪽 0.107', 'lbl sm');
        s += T(40, 120, '노출 160,000', 'lbl k');
        s += `<rect class="f-a" x="${X1(1.156).toFixed(1)}" y="108" width="${(X1(1.264) - X1(1.156)).toFixed(1)}" height="16"/>`;
        s += T(X1(1.264) + 8, 120, '한쪽 0.054', 'lbl sm');
        s += ruler(60, 146, 410, [[60, '', '1.00%'], [X1(1.10), '', '1.10%'], [X1(1.20), '', '1.20%'], [X1(1.30), '', '1.30%'], [470, '', '1.40%']], { h: 12 });
        s += tool(40, 200, 320, { label: '표준오차 = 루트( p 곱하기 (1 − p) 나누기 노출 수 )', sub: '노출 수가 4배면 루트 4 = 2 로 나뉩니다' });
        s += tag(374, 210, '폭은 절반', 'k');
        s += T(40, 270, '노출을 4배로 모으면 구간의 폭이 절반이 됩니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 3. 95% 신뢰구간 — 100번 중 다섯 번은 놓친다 ----------
    (function () {
        const S = 'st-interval'; if (!has(S)) return; let s = '';
        // 시드 9 로 노출 40,000 을 100번 뽑았을 때의 클릭 수. p1_sim.py 를 그대로 돌린 값이다
        const KS = [520, 513, 480, 460, 506, 490, 515, 460, 517, 511, 455, 430, 459, 488, 453, 494, 484, 481, 476, 528,
            471, 493, 456, 492, 477, 442, 500, 469, 496, 496, 499, 454, 485, 442, 476, 454, 527, 494, 479, 509,
            506, 466, 514, 471, 484, 438, 503, 453, 504, 486, 476, 499, 471, 494, 517, 464, 504, 469, 521, 485,
            512, 486, 447, 475, 483, 499, 474, 478, 497, 460, 468, 445, 503, 487, 522, 461, 471, 481, 498, 449,
            489, 453, 474, 501, 500, 448, 473, 468, 423, 476, 482, 518, 479, 496, 455, 499, 492, 481, 450, 480];
        const TRUE = 1.21, Y = v => 34 + (1.48 - v) * 351.85;
        s += T(40, 22, '참 클릭률 1.21% 에서 노출 40,000 을 100번 뽑아 구간을 그렸습니다', 'lbl sm');
        let miss = 0;
        KS.forEach((k, i) => {
            const p = k / 400, se = Math.sqrt((p / 100) * (1 - p / 100) / 40000) * 100;
            const lo = p - 1.96 * se, hi = p + 1.96 * se, out = !(lo <= TRUE && TRUE <= hi);
            if (out) miss++;
            s += `<rect class="f-${out ? 'b' : 'a'}" x="${(40 + i * 3.84).toFixed(1)}" y="${Y(hi).toFixed(1)}" width="2.2" height="${(Y(lo) - Y(hi)).toFixed(1)}"/>`;
        });
        s += `<rect class="f-b" x="36" y="${(Y(TRUE) - 0.8).toFixed(1)}" width="388" height="1.6"/>`;
        s += T(428, Y(TRUE) + 4, '참값 1.21%', 'lbl b');
        s += tag(40, 236, '품은 구간 ' + (100 - miss) + '개', 'a');
        s += tag(160, 236, '놓친 구간 ' + miss + '개', 'b');
        s += T(276, 249, '놓친 다섯 번은 모두 낮게 나온 때입니다', 'lbl sm');
        s += T(40, 274, '구간이 참값을 품는 횟수가 100번 중 95번쯤입니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 4. 검정통계량 — 차이를 흔들림으로 나눈다 ----------
    (function () {
        const S = 'st-tstat'; if (!has(S)) return; let s = '';
        const Z = z => 150 + z * 85;
        s += T(40, 22, '차이를 흔들림으로 나눈 값이 검정통계량입니다', 'lbl sm');
        s += T(40, 54, '노출 40,000 씩', 'lbl k');
        s += T(40, 70, '0.13 ÷ 0.0752', 'lbl sm');
        s += `<rect class="f-a" x="150" y="48" width="${(1.73 * 85).toFixed(1)}" height="20"/>`;
        s += T(500, 63, 'z 1.73', 'lbl k', 'end');
        s += T(40, 114, '노출 160,000 씩', 'lbl k');
        s += T(40, 130, '0.13 ÷ 0.0376', 'lbl sm');
        s += `<rect class="f-a" x="150" y="108" width="${(3.46 * 85).toFixed(1)}" height="20"/>`;
        s += T(500, 123, 'z 3.46', 'lbl k', 'end');
        s += vbar(Z(1.96), 40, 102, 'b');
        s += T(Z(1.96), 34, '문턱 1.96', 'lbl b', 'middle');
        s += tag(150, 158, '양쪽 p 0.084 — 확인 못 함', 'k');
        s += tag(150, 184, '양쪽 p 0.0005 — 확인', 'k');
        s += lines(40, 226, ['차이 0.13 은 그대로인데 노출이 4배가 되면 z 가 2배가 됩니다', '흔들림이 절반으로 줄기 때문입니다']);
        s += T(40, 274, '문턱을 넘으면 확인이고, 못 넘으면 아직 모른다는 뜻입니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 5. t 검정 — 평균의 차이와 자유도 ----------
    (function () {
        const S = 'st-ttest'; if (!has(S)) return; let s = '';
        s += T(40, 22, '주문 금액의 평균을 견줍니다 (각 30건, 표준편차 18,000원)', 'lbl sm');
        s += T(40, 61, '소재 A', 'lbl k');
        s += hbar(100, 50, 250, 42300 / 60000, 'a');
        s += T(360, 61, '42,300원', 'lbl k');
        s += T(40, 89, '소재 B', 'lbl k');
        s += hbar(100, 78, 250, 47900 / 60000, 'a');
        s += T(360, 89, '47,900원', 'lbl k');
        s += T(40, 117, '흩어짐', 'lbl sm');
        s += hbar(100, 106, 250, 18000 / 60000, 'c');
        s += T(360, 117, '18,000원', 'lbl sm');
        s += tool(40, 146, 300, { label: '차이 5,600원 나누기 표준오차 4,648원 = 1.20', sub: '표준오차 = 18,000 곱하기 루트( 2 나누기 30 )' });
        s += tag(360, 148, '문턱 2.00', 'b');
        s += tag(360, 176, '확인 못 함', 'k');
        s += lines(40, 212, ['자유도 58 — 두 무리 30건씩에서 평균 둘을 뺀 수입니다', '자유도가 커지면 문턱은 1.96 에 가까워집니다']);
        s += T(40, 270, '평균은 5,600원 벌어졌지만 흔들림이 4,648원이라 못 넘습니다', 'lbl');
        svg(S, s);
    })();

    // ---------- 6. 분산 검정 — 무리 사이 차이와 무리 안 흔들림 ----------
    (function () {
        const S = 'st-variance'; if (!has(S)) return; let s = '';
        const X6 = v => 60 + (v - 1.00) * 1366.7;
        s += T(40, 22, '소재가 셋이면 무리 사이 차이를 무리 안 흔들림으로 나눕니다', 'lbl sm');
        s += vbar(X6(1.147), 44, 96, 'b');
        s += T(X6(1.147), 38, '전체 1.147%', 'lbl b', 'middle');
        [['소재 A 1.08%', 1.08], ['소재 B 1.21%', 1.21], ['소재 C 1.15%', 1.15]].forEach((r, i) => {
            s += ctag(X6(r[1]), 50 + i * 26, r[0], 'a');
        });
        s += ruler(60, 148, 410, [[60, '', '1.00%'], [X6(1.10), '', '1.10%'], [X6(1.20), '', '1.20%'], [470, '', '1.30%']], { h: 12 });
        s += tool(40, 200, 280, { label: '무리 사이 0.0169 나누기 무리 안 0.0113', sub: '= F 1.49' });
        s += tag(336, 202, '문턱 3.00', 'b');
        s += tag(336, 226, '확인 못 함', 'k');
        s += T(40, 270, '세 소재의 차이가 무리 안 흔들림의 1.49배입니다', 'lbl');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
