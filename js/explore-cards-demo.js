/**
 * explore-cards-demo.js — 탐색과 채점 카드 네 장
 *
 * 노출을 어떻게 나누고 그 결과를 어떻게 채점하나. 네 자리를 카드 한 장씩으로.
 * 처방 넷은 밀려난 소재에 얼마를 떼어 주나, A/B 와 밴딧은 남는 성적표가 어떻게 다른가,
 * UCB1 은 맥락을 뭉치면 무엇을 놓치나, 이중 강건은 재료 하나가 틀려도 왜 버티나.
 * 색은 css/style.css 의 카드 부품 블록이 정한다 — 파랑 나은 쪽과 결론, 회색 견주는 값,
 * 벽돌색 손해와 틀린 값. 숫자는 전부 그 글의 가상 데이터 값이다.
 *
 * 호스트(#mc-<key>)가 없는 카드는 건너뛴다. ?card=key 가 붙으면 그 카드만 남긴다.
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, tag, tool, list, arrow, dots, svg, hbar } = window.CardKit;
    const has = id => !!document.getElementById(id);
    const rect = (x, y, w, h, cls) => `<rect class="${cls}" x="${x}" y="${y}" width="${w}" height="${h}"/>`;
    const line = (x1, y1, x2, y2, cls) => `<line class="${cls}" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}"/>`;

    // ---------- 1. 처방 넷 (feedback-loop-remedies) ----------
    (function () {
        const S = 'mc-remedies'; if (!has(S)) return; let s = '';
        s += T(40, 26, '밀려난 소재를 되살리는 처방 넷 (하루 노출 20,000건 기준)', 'lbl sm');
        s += T(40, 50, '처방', 'lbl sm') + T(160, 50, '탐색에 쓰는 노출', 'lbl sm') + T(292, 50, '건수', 'lbl sm') + T(352, 50, '되살린 날', 'lbl sm') + T(432, 50, '40일 클릭', 'lbl sm');
        s += line(40, 56, 490, 56, 'tick');
        [['ε 탐색 5%', 0.625, 'a', '1,000건', '여드레', '18,541'],
        ['낙관 초기값', 0, 'c', '정한 값 없음', '사흘', '18,546'],
        ['강제 슬롯 8%', 1, 'a', '1,600건', '사흘', '18,515'],
        ['역확률 가중', 0, 'c', '0건', '못 되살림', '변화 없음']].forEach((r, i) => {
            const y = 66 + i * 28;
            s += T(40, y + 11, r[0], 'lbl k');
            s += hbar(160, y, 120, r[1], r[2]);
            s += T(292, y + 11, r[3], 'lbl sm');
            s += T(352, y + 11, r[4], r[4] === '못 되살림' ? 'lbl b' : 'lbl k');
            s += T(432, y + 11, r[5], 'lbl k');
        });
        s += tag(40, 190, '기본 고리 17,350건 — 진짜 값을 알고 배분했다면 18,831건', 'b');
        s += T(40, 226, '기본이 40일 동안 1,481건, 7.9%를 흘립니다. 클릭 한 건 ₩500 이면 ₩740,500 입니다', 'lbl sm');
        s += T(40, 246, 'ε 탐색이 느린 이유는 한 세대에 주는 몫이 125건이고 강제 슬롯은 400건이기 때문입니다', 'lbl sm');
        s += T(40, 280, '탐색은 그날의 매출을 조금 내주고 정보를 사는 일입니다. 역확률 가중만 노출을 안 씁니다', 'lbl');
        svg(S, s, 300);
    })();

    // ---------- 2. A/B 와 밴딧 (ab-test-vs-mab) ----------
    (function () {
        const S = 'mc-abmab'; if (!has(S)) return; let s = '';
        s += T(40, 26, '소재 둘에 노출 10만 건. 진짜 클릭률은 소재 A 2.0%, 소재 B 3.0%', 'lbl sm');
        s += T(40, 56, 'A/B 50:50 고정', 'lbl k');
        s += rect(160, 44, 300, 16, 'track') + rect(160, 44, 150, 16, 'f-c') + rect(310, 44, 150, 16, 'f-a');
        s += T(160, 78, '소재 A 50,000', 'lbl sm') + T(330, 78, '소재 B 50,000', 'lbl sm');
        s += tag(40, 70, '총 2,521클릭', 'c');
        s += T(40, 132, '밴딧 (적응형)', 'lbl k');
        s += rect(160, 120, 300, 16, 'track') + rect(160, 120, 13, 16, 'f-c') + rect(173, 120, 287, 16, 'f-a');
        s += T(160, 154, '소재 A 4,171', 'lbl sm') + T(300, 154, '소재 B 95,829', 'lbl sm');
        s += tag(40, 146, '총 2,980클릭', 'a');
        s += T(40, 192, '남는 성적표 — 소재 A 의 95% 구간이 얼마나 넓은가', 'lbl sm');
        s += T(40, 218, 'A/B', 'lbl k') + rect(110, 208, 24, 13, 'f-a') + T(144, 218, '±0.124%p', 'lbl k');
        s += T(40, 242, '밴딧', 'lbl k') + rect(110, 232, 88, 13, 'f-b') + T(208, 242, '±0.453%p — 3.7배 넓습니다', 'lbl b');
        s += tag(40, 254, '진짜 차이가 2.0% 대 2.1% 면 밴딧이 노출의 94%를 열세 소재에 몰아줍니다', 'b');
        s += T(40, 294, '밴딧은 이긴 쪽을 잘 알고 진 쪽을 잘 모릅니다. 효과가 작으면 A/B 가 안전합니다', 'lbl');
        svg(S, s, 320);
    })();

    // ---------- 3. 맥락을 뭉치면 (ucb-family) ----------
    (function () {
        const S = 'mc-ucbctx'; if (!has(S)) return; let s = '';
        s += T(40, 26, '지면과 시간대에 따라 이기는 소재가 바뀝니다 (진짜 클릭률)', 'lbl sm');
        s += T(40, 50, '조합', 'lbl sm') + T(200, 50, '소재 A', 'lbl sm') + T(280, 50, '소재 B', 'lbl sm') + T(370, 50, '이 조합의 승자', 'lbl sm');
        s += line(40, 56, 460, 56, 'tick');
        [['뉴스 오전', '8%', '3%', 'A'], ['뉴스 저녁', '2%', '6%', 'B'],
        ['커뮤니티 오전', '3%', '7%', 'B'], ['커뮤니티 저녁', '6%', '4%', 'A']].forEach((r, i) => {
            const y = 76 + i * 22;
            s += T(40, y, r[0], 'lbl k') + T(200, y, r[1], 'lbl') + T(280, y, r[2], 'lbl') + T(370, y, r[3], 'lbl k');
        });
        s += line(40, 172, 460, 172, 'tick');
        s += T(40, 190, '전체 평균 — 뭉쳐 보면', 'lbl b') + T(200, 190, '4.75%', 'lbl b') + T(280, 190, '5.0%', 'lbl b') + T(370, 190, 'B', 'lbl b');
        s += tag(40, 202, 'UCB1 은 마지막 줄만 봅니다', 'b');
        s += T(40, 244, '4,000회를 돌리면', 'lbl sm');
        s += tag(40, 254, '뭉쳐 보면 A 1,943 대 B 2,057 로 반반. 클릭 192', 'c');
        s += tag(40, 280, '맥락별로 쪼개면 클릭 245 — 27.6% 더 많습니다', 'a');
        s += T(40, 320, '조합마다 정답이 다른데 평균 하나로 뭉치면 뉴스 오전에서 매번 절반을 놓칩니다', 'lbl');
        svg(S, s, 340);
    })();

    // ---------- 4. 이중 강건 (doubly-robust) ----------
    (function () {
        const S = 'mc-dr'; if (!has(S)) return; let s = '';
        s += T(40, 26, '지난주 로그로 새 모델을 채점합니다. 재료가 둘입니다', 'lbl sm');
        s += list(40, 38, 200, 44, [{ t: '재료 1   성향점수', cls: 'h' }, '옛 정책이 그 광고를 고를 확률']);
        s += list(40, 96, 200, 44, [{ t: '재료 2   예측 모델', cls: 'h' }, '클릭 확률을 미리 찍어 둔 값']);
        s += tool(280, 68, 150, { label: '예측을 먼저 깔고', sub: '빗나간 몫에만 가중합니다' });
        s += arrow('dr1', 'M240,60 C260,60 268,80 276,84', 'a', { svg: S });
        s += arrow('dr2', 'M240,118 C260,118 268,98 276,94', 'a', { svg: S });
        s += dots('dr1', 'a', { n: 1, dur: 2.2 }) + dots('dr2', 'a', { n: 1, dur: 2.2 });
        s += T(40, 168, '재료 하나가 틀렸을 때 — 새 정책의 진짜 값은 2.807%', 'lbl sm');
        s += T(40, 190, '틀린 재료', 'lbl sm') + T(160, 190, '예측만 쓰기', 'lbl sm') + T(270, 190, '역수로 세기', 'lbl sm') + T(380, 190, '두 겹', 'lbl sm');
        s += line(40, 196, 460, 196, 'tick');
        s += T(40, 214, '예측 모델', 'lbl k') + T(160, 214, '1.980%', 'lbl b') + T(270, 214, '2.776%', 'lbl') + tag(376, 202, '2.774%', 'a');
        s += T(40, 244, '성향점수', 'lbl k') + T(160, 244, '2.807%', 'lbl') + T(270, 244, '2.442%', 'lbl b') + tag(376, 232, '2.797%', 'a');
        s += T(40, 274, '둘 중 하나만 맞아도 진짜 값 옆에 붙습니다', 'lbl k');
        s += T(40, 294, '대신 흔들림은 0.809%에서 0.806%로 거의 그대로입니다', 'lbl sm');
        s += T(40, 324, '재료 둘을 겹쳐 두면 하나가 틀려도 버팁니다. 흔들림이 줄지는 않습니다', 'lbl');
        svg(S, s, 350);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
