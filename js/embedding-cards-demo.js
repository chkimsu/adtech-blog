/**
 * embedding-cards-demo.js — 임베딩 카드 네 장
 *
 * 상품 이름 한 줄이 숫자 384개가 되고, 가까운 상품을 찾기까지를 카드 한 장씩으로 그린다.
 * 글자 두 개 조각을 384칸에 더하는 장난감 임베딩, 두 벡터의 각과 코사인, 3,000건 전수 검색과 해시 충돌,
 * 랜덤 투영 해시의 묶음만 보는 근사 검색과 재현율@10.
 * 색은 css/style.css 의 카드 부품 블록이 토큰으로 정한다. 파랑은 코드가 하는 일, 벽돌색은 검색어,
 * 먹색은 벡터와 칸, 회색은 놓친 상품이고, 점선 상자는 가상 값(상품 이름)이다.
 *
 * 숫자(384, 19칸, 0.229, 1.000, 3,000번, 1,152,000번, 점수, 칸 번호, 거리 계산, 재현율@10)는
 * embeddings-vector-search 글의 파이썬 블록 셋이 찍은 출력에서 옮겼다. 글의 블록을 고치면 여기도 고친다.
 *
 * ?card=key 가 붙으면 그 카드만 남긴다 (글 안에 iframe 으로 넣을 때 쓴다).
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, box, tag, list, arrow, svg, hbar } = window.CardKit;
    const has = id => !!document.getElementById(id);

    // ---------- 1. 이름 한 줄이 숫자 384개 ----------
    (function () {
        const S = 'ev-vector'; if (!has(S)) return; let s = '';
        s += list(40, 12, 446, 36, [
            { t: '첫 상품, 가상 이름', cls: 'h' },
            '하이라이프 와이드 카키 캠핑테이블 CG766',
        ]);
        s += T(40, 70, '띄어쓰기를 지우고 글자 두 개씩 겹쳐 자른다', 'lbl k');
        ['하이', '이라', '라이', '이프', '...', '캠핑', '...', '66'].forEach((p, i) => {
            s += tag(40 + i * 56, 78, p, p === '...' ? 'c' : 'b');
        });
        s += arrow('evv0', 'M60,104 L60,128', 'a', { svg: S });
        s += T(80, 120, '조각마다 crc32 로 0~383 칸 하나에 1 을 더하고, 길이로 나눈다', 'lbl sm');
        s += hbar(40, 134, 440, 0, 'k', 18);
        [19, 40, 82].forEach(i => { s += `<rect class="f-a" x="${40 + Math.round(i * 440 / 384)}" y="134" width="3" height="18"/>`; });
        s += T(40, 168, '칸 0', 'lbl sm') + T(480, 168, '칸 383', 'lbl sm', 'end');
        s += T(40, 192, '0 이 아닌 칸 셋: [19] 0.229, [40] 0.229, [82] 0.229', 'lbl');
        s += T(40, 216, '숫자 384개, 0 이 아닌 칸 19개, 앞 8칸은 모두 0', 'lbl');
        s += T(40, 240, '길이(L2 노름) 1.000', 'lbl k');
        s += T(40, 266, '학습이 없어 가까움은 조각이 떨어진 칸으로만 정해집니다', 'lbl sm');
        s += T(40, 284, '상품 3,000건은 이름 틀에 낱말을 끼운 가상 데이터입니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 2. 두 벡터의 각과 코사인 ----------
    (function () {
        const S = 'ev-cosine'; if (!has(S)) return; let s = '';
        s += arrow('evc0', 'M60,180 L230,180', 'b', { svg: S });
        s += arrow('evc1', 'M60,180 L200,70', 'a', { svg: S });
        s += arrow('evc2', 'M60,180 L60,40', 'k', { svg: S });
        s += T(238, 184, '검색어', 'lbl');
        s += T(206, 66, '가까운 상품', 'lbl');
        s += T(68, 36, '같은 칸이 없는 상품', 'lbl sm');
        s += T(96, 168, '각이 작다', 'lbl sm');
        s += T(290, 60, '코사인 = 내적 ÷ (두 길이의 곱)', 'lbl k');
        s += T(290, 90, '각 0 이면 1', 'lbl');
        s += T(290, 112, '직각이면 0', 'lbl');
        s += T(290, 134, '정반대면 -1', 'lbl');
        s += T(290, 168, '길이가 1 이면 코사인 = 내적', 'lbl k');
        s += T(40, 230, '장난감 벡터는 음수 칸이 없어 코사인이 0 에서 1 사이입니다', 'lbl');
        s += T(40, 254, '같은 칸을 하나도 나눠 갖지 않으면 0 입니다', 'lbl sm');
        s += T(40, 274, '모든 벡터를 길이 1 로 맞춰 두어 내적만 계산해도 됩니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 3. 3,000건 전수 검색과 해시 충돌 ----------
    (function () {
        const S = 'ev-bruteforce'; if (!has(S)) return; let s = '';
        s += tag(40, 12, '헤드셋', 'b') + T(110, 25, '거리 계산 3,000번, 곱셈 3,000 × 384 = 1,152,000번', 'lbl sm');
        const rows = [
            ['1위', 0.463, '별랩 슬림 블랙 헤드폰 FL159'],
            ['2위', 0.392, '별랩 방수 카키 텀블러 ED267'],
            ['3위', 0.378, '다온 슬림 그레이 텀블러 ED629'],
            ['10위', 0.354, '별랩 슬림 블랙 여행가방 LF887'],
        ];
        rows.forEach(([r, v, name], i) => {
            const y = 44 + i * 26;
            s += T(40, y + 11, r, 'lbl k') + hbar(80, y, 120, v, 'a', 13) + T(206, y + 11, v.toFixed(3), 'lbl') + T(250, y + 11, name, 'lbl sm');
        });
        s += T(40, 166, '같은 칸에 떨어진 조각, 해시 충돌', 'lbl k');
        s += box(40, 176, 86, 22, '헤드 [346]', 'b', 10) + box(40, 206, 86, 22, '드셋 [348]', 'b', 10);
        s += T(140, 191, '1위: 랩슬, 림블, 헤드 / 2위: 러e', 'lbl sm');
        s += T(140, 221, '2위: 모델 번호의 ed', 'lbl sm');
        s += T(40, 256, '텀블러는 글자가 다른 조각이 같은 칸을 써서 2위에 섰습니다', 'lbl');
        s += T(40, 278, '캠핑 의자는 10위 점수 이상 17건, 스니커즈는 27건입니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 4. 해시 묶음만 보는 근사 검색 ----------
    (function () {
        const S = 'ev-ann'; if (!has(S)) return; let s = '';
        s += T(40, 20, '테이블 6개 × 비트 10개, 상품이 든 묶음 4,813개', 'lbl k');
        s += T(40, 44, '검색어', 'lbl sm') + T(130, 44, '거리 계산 (전수 3,000번)', 'lbl sm') + T(380, 44, '재현율@10', 'lbl sm');
        const rows = [
            ['같은 묶음만', null],
            ['캠핑 의자', 26, 0.1, 'c'], ['헤드셋', 19, 0.0, 'c'], ['스니커즈', 21, 0.2, 'c'],
            ['이웃 묶음까지', null],
            ['캠핑 의자', 254, 0.8, 'a'], ['헤드셋', 176, 0.7, 'a'], ['스니커즈', 142, 0.9, 'a'],
        ];
        let y = 54;
        rows.forEach(([name, n, r, cls]) => {
            if (n === null) { s += T(40, y + 12, name, 'lbl k'); y += 20; return; }
            s += T(40, y + 11, name, 'lbl sm') + hbar(130, y, 180, n / 3000, 'k', 12) + T(316, y + 11, n + '번', 'lbl sm');
            s += hbar(380, y, 80, r, cls, 12) + T(466, y + 11, r.toFixed(1), 'lbl sm');
            y += 20;
        });
        s += T(40, 236, '이웃 묶음은 비트 하나만 다른 묶음 10개입니다', 'lbl');
        s += T(40, 258, '이웃까지 보면 전수의 4.7~8.5% 만 재고, 10위 점수 이상인 상품을 일부 놓칩니다', 'lbl sm');
        s += T(40, 278, '맞힌 것은 전수 검색의 10위 점수 이상인 상품입니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
