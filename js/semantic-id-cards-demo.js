/**
 * semantic-id-cards-demo.js — Semantic ID 카드 네 장
 *
 * 상품 300건의 벡터를 세 단의 코드북으로 잔차 양자화해 코드 셋을 붙이고, 코드 트리에서 빔 탐색으로 상품을 꺼내는 자리를 카드 한 장씩으로 그린다.
 * 3단 코드북, 코드 트리, 단마다 고르기, 새 상품.
 * 색은 css/style.css 의 카드 부품 블록이 토큰으로 정한다. 파랑은 상품과 코드북, 벽돌색은 회원 A 의 질의와 빔이 고른 것,
 * 먹색은 트리의 노드와 상품이 받은 코드, 회색은 빔에서 빠진 것과 비교할 기준값이고, 점선은 가상 값(회원 A 가 본 상품, 새 상품)이다.
 *
 * 숫자는 전부 generative-retrieval-semantic-id 글의 파이썬 블록 셋이 찍은 출력에서 옮긴 값이다. 상품과 회원 A 가 본 상품 셋,
 * 새 상품 10건은 가상 값이다. 글의 블록을 고치면 여기도 고친다.
 *
 * ?card=key 가 붙으면 그 카드만 남긴다 (글 안에 iframe 으로 넣을 때 쓴다).
 * 그리기 부품은 card-kit.js 에 있다.
 */
(function () {
    'use strict';
    const { T, box, tool, list, arrow, svg } = window.CardKit;
    const has = id => !!document.getElementById(id);
    // 코드 16개를 칸 16개로 그린다. 고른 코드만 채우고 나머지는 눈금 칸이다
    const cells = (x, y, chosen, cls, w = 17, step = 19) => {
        let r = '';
        for (let j = 0; j < 16; j++) {
            const cx = x + j * step;
            if (j === chosen) r += box(cx, y, w, 18, String(j), cls, 9);
            else r += `<rect class="track" x="${cx}" y="${y}" width="${w}" height="18"/>` +
                T(cx + w / 2, y + 12.5, String(j), 'lbl sm', 'middle');
        }
        return r;
    };

    // ---------- 1. 3단 코드북 ----------
    (function () {
        const S = 'si-codebook'; if (!has(S)) return; let s = '';
        s += T(40, 20, '상품 벡터가 세 단의 코드북을 차례로 지나 코드 셋이 됩니다', 'lbl sm');
        s += box(40, 30, 190, 20, '상품 0 의 벡터 384차원, 길이 1', 'a', 10);
        // [단, 상품 0 이 받은 코드, 가장 큰 코드, 그 코드의 상품 수, 단을 마친 잔차 길이 평균] 블록 1 의 3단계가 찍은 값
        const levels = [[1, 8, 15, 34, '0.837'], [2, 6, 7, 55, '0.778'], [3, 9, 9, 284, '0.748']];
        levels.forEach(([lv, code, big, n, norm], i) => {
            const y = 72 + i * 58;
            s += T(40, y + 13, `${lv}단 코드북`, 'lbl k');
            s += cells(110, y, code, 'k');
            s += T(500, y + 13, `코드 ${code}`, 'lbl k', 'end');
            s += T(110, y + 33, `잔차 길이 평균 ${norm}, 가장 큰 코드 ${big} 에 ${n}건`, i === 2 ? 'lbl k' : 'lbl');
            if (i < 2) s += arrow(`si-cb-${i}`, `M60,${y + 38} L60,${y + 54}`, 'k', { svg: S });
        });
        s += arrow('si-cb-in', 'M60,52 L60,68', 'a', { svg: S });
        s += T(70, 64, '1단은 벡터를, 2단과 3단은 앞 단의 중심을 뺀 잔차를 나눕니다', 'lbl sm');
        s += T(40, 262, '상품 0 의 코드 셋 (8, 6, 9), 넷째 자리까지 (8, 6, 9, 0)', 'lbl k');
        s += T(40, 282, '코드북 벡터 48개. 3단 코드 9 의 초기 중심은 길이 0 (단마다 같은 상품에서 출발하는 규칙)', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 2. 코드 트리 ----------
    (function () {
        const S = 'si-tree'; if (!has(S)) return; let s = '';
        s += T(40, 20, '코드 셋을 첫째 코드부터 가지로 나누면 트리가 됩니다', 'lbl sm');
        s += T(40, 45, '1단', 'lbl k');
        s += cells(76, 32, 2, 'k', 19, 23);
        s += T(500, 45, '노드 16개', 'lbl', 'end');
        s += arrow('si-tr-1', 'M86,52 L86,72', 'k', { svg: S });
        s += T(40, 89, '2단', 'lbl k');
        s += box(76, 76, 64, 18, '(2, 7)', 'k', 10);
        s += T(152, 89, '… 2단 노드는 모두 138개', 'lbl');
        s += arrow('si-tr-2', 'M86,96 L86,114', 'k', { svg: S });
        s += T(40, 131, '리프', 'lbl k');
        s += box(76, 118, 84, 18, '(2, 7, 9)', 'k', 10);
        s += T(172, 131, '… 리프는 모두 147개, 이 리프에 상품 7건', 'lbl');
        // 가장 큰 리프의 상품 일곱, 넷째 자리 차례대로. 블록 1 의 4단계가 찍은 줄
        const items = ['별랩 심플 그레이 블루투스스피커', '다온 방수 그레이 유모차', '별랩 방수 그레이 캠핑테이블',
            '별랩 와이드 그레이 러닝화', '다온 방수 그레이 선글라스', '온팩토리 와이드 그레이 블루투스스피커', '숲결 방수 그레이 립밤'];
        s += list(76, 144, 414, 108, items.map((name, n) => ({ t: `(2, 7, 9, ${n})  ${name}`, cls: n === 0 ? 'h' : '' })));
        s += T(40, 272, '코드 셋 4,096가지 가운데 상품이 있는 것 147가지, 함께 쓰는 묶음 73개', 'lbl');
        s += T(40, 290, '넷째 자리까지 붙이면 id 300개가 모두 다릅니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 3. 단마다 고르기 ----------
    (function () {
        const S = 'si-beam'; if (!has(S)) return; let s = '';
        s += T(40, 20, '회원 A 가 본 상품 셋의 평균 벡터에서 출발해 단마다 3개를 남깁니다', 'lbl sm');
        s += list(40, 28, 450, 34, ['본 상품 (가상): 26 러닝화 (10, 12, 9), 34 러닝화 (6, 0, 9), 44 여행가방 (13, 13, 13)']);
        // [단, 후보 수, 남긴 코드와 점수] 블록 2 의 3단계가 찍은 값. 점수는 남은 잔차의 거리 제곱
        const kept = [[1, 16, ['13  0.343', '6  0.357', '10  0.386']],
            [2, 31, ['(13, 0)  0.317', '(13, 6)  0.325', '(6, 0)  0.336']],
            [3, 3, ['(13, 0, 9)  0.320', '(13, 6, 9)  0.328', '(6, 0, 9)  0.336']]];
        kept.forEach(([lv, n, picks], i) => {
            const y = 78 + i * 30;
            s += T(40, y + 13, `${lv}단 후보 ${n}개`, 'lbl k');
            picks.forEach((p, j) => { s += box(150 + j * 116, y, 108, 18, p, 'b', 9.5); });
        });
        s += T(40, 186, '리프 셋의 상품 4건, 5건, 2건에서 본 상품 34 를 빼고 10건을 꺼냈습니다', 'lbl');
        s += T(40, 212, '전수 코사인 상위 10건이 빔의 어느 단에서 빠졌나 (왼쪽이 1위)', 'lbl k');
        // 블록 2 의 4단계가 찍은 줄. 0 은 빔도 꺼낸 상품
        const gone = [2, 1, 1, 2, 1, 1, 0, 2, 1, 1];
        gone.forEach((g, i) => { s += box(40 + i * 45, 222, 41, 18, g ? `${g}단` : '꺼냄', g ? 'c' : 'b', 9.5); });
        s += T(40, 262, '1단에서 빠짐 6건, 2단에서 빠짐 3건, 빔도 꺼냄 1건 (전수 7위 여행가방)', 'lbl');
        s += T(40, 282, '빔이 꺼낸 10건 가운데 온팩토리 9건, 전수 상위 10건 가운데 러닝화 6건', 'lbl sm');
        svg(S, s);
    })();

    // ---------- 4. 새 상품 ----------
    (function () {
        const S = 'si-cold'; if (!has(S)) return; let s = '';
        s += T(40, 20, '새 상품 10건이 코드북을 다시 학습하지 않고 코드를 받습니다', 'lbl sm');
        s += tool(40, 30, 150, { label: 'encode', sub: '코드북 그대로, k-means 없음' });
        s += T(206, 46, '단마다 학습해 둔 코드북에서 가장 가까운 중심을 고릅니다', 'lbl sm');
        s += T(206, 62, '같은 방법으로 다시 적은 학습 상품 300건은 코드 셋이 모두 같습니다', 'lbl sm');
        s += arrow('si-cold-in', 'M60,72 L60,82', 'k', { svg: S });
        // [id, 품목, 넷째 자리까지의 코드, 표시] 블록 3 의 2단계와 3단계가 찍은 줄. b 는 빔이 꺼낸 상품, n 은 새 리프
        const items = [[300, '백팩', '(11, 1, 9, 3)'], [301, '텀블러', '(13, 6, 9, 5)', 'b'], [302, '립밤', '(13, 7, 9, 2)'],
            [303, '유모차', '(4, 4, 9, 0)', 'n'], [304, '캠핑테이블', '(6, 7, 9, 5)'], [305, '블루투스스피커', '(11, 11, 9, 3)'],
            [306, '스니커즈', '(11, 8, 9, 0)', 'n'], [307, '손목시계', '(13, 0, 9, 4)', 'b'], [308, '크로스백', '(0, 6, 9, 3)'],
            [309, '텀블러', '(13, 12, 9, 1)']];
        s += `<rect class="list" x="40" y="84" width="450" height="80"/>`;
        items.forEach(([id, noun, code, mark], i) => {
            const x = i < 5 ? 49 : 270, y = 98 + (i % 5) * 14;
            const cls = mark === 'b' ? 'list-t b' : mark === 'n' ? 'list-t h' : 'list-t';
            s += T(x, y, `${id} ${noun} ${code}${mark === 'n' ? '  새 리프' : ''}`, cls);
        });
        s += T(40, 184, '있던 리프에 8건, 새 리프 2건. 있던 300건의 넷째 자리는 그대로', 'lbl k');
        s += T(40, 204, '회원 A 의 빔이 바로 꺼낸 새 상품: 307 손목시계, 301 텀블러', 'lbl b');
        s += `<line class="split" x1="40" y1="216" x2="490" y2="216"/>`;
        s += T(40, 236, '상품 id 임베딩 표 (설명): 학습한 id 에만 행이 있습니다', 'lbl k');
        // id 297~299 는 행이 있고, 300~309 는 없다. 블록 3 의 4단계가 찍은 수
        for (let i = 0; i < 13; i++) {
            const id = 297 + i, x = 40 + i * 35;
            if (id < 300) s += box(x, 246, 31, 18, String(id), 'a', 9);
            else s += `<rect class="track" x="${x}" y="246" width="31" height="18"/>` + T(x + 15.5, 258.5, String(id), 'lbl sm', 'middle');
        }
        s += T(40, 284, '행 300개, 새 상품 10건은 모두 행이 없습니다. 행이 생기는 때는 블록이 재지 않았습니다', 'lbl sm');
        svg(S, s);
    })();

    // ---------- ?card=key ----------
    const only = new URLSearchParams(location.search).get('card');
    if (only) document.querySelectorAll('.tg-card').forEach(c => { if (c.dataset.card !== only) c.hidden = true; });
})();
